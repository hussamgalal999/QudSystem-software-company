    def test_default_denied_secret_path_is_rejected_even_when_allowlisted(self) -> None:
        codex = self.bin / "codex"
        codex.write_text(
            "#!/usr/bin/env python3\n"
            "from pathlib import Path\n"
            "Path('.env').write_text('API_KEY=DO_NOT_EXPORT\\n', encoding='utf-8')\n"
            "print('{}')\n",
            encoding="utf-8",
        )
        codex.chmod(0o755)
        manifest_path = self.write_manifest([{
            "id": "denied-secret", "agent": "codex", "mode": "implement", "base_ref": "HEAD",
            "allowed_paths": [".env"], "prompt": "write a fixture file",
        }])
        task = agent_fleet.load_manifest(manifest_path)["tasks"][0]
        artifact_dir = self.artifacts / "deny-test"
        worktree_root = self.worktrees / "deny-test"
        artifact_dir.mkdir(parents=True)
        worktree_root.mkdir(parents=True)
        prepared = agent_fleet.prepare_task(self.repo, task, "deny-test-12345678", worktree_root, artifact_dir)
        result = agent_fleet.execute_task(prepared, artifact_dir, timeout=60, capture_logs=True)
        self.assertEqual(result["status"], "scope_violation")
        self.assertFalse(result["logs_exported"])
        self.assertIsNone(result["stdout_path"])
        self.assertIsNone(result["stderr_path"])
        self.assertEqual(result["scope_violations"], [".env"])
        self.assertFalse(result["patch_exported"])
        for artifact in artifact_dir.iterdir():
            if artifact.is_file():
                self.assertNotIn("API_KEY=DO_NOT_EXPORT", artifact.read_text(encoding="utf-8"))
