from __future__ import annotations

import argparse
import contextlib
import hashlib
import io
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from scripts import agent_fleet


class AgentFleetTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.tmp = Path(self.temp.name)
        self.repo = self.tmp / "repo"
        self.repo.mkdir()
        subprocess.run(["git", "init", "-b", "main"], cwd=self.repo, check=True, capture_output=True)
        subprocess.run(["git", "config", "user.email", "fleet-test@example.invalid"], cwd=self.repo, check=True)
        subprocess.run(["git", "config", "user.name", "Fleet Test"], cwd=self.repo, check=True)
        (self.repo / "README.md").write_text("fixture\n", encoding="utf-8")
        (self.repo / ".gitignore").write_text(".env\n", encoding="utf-8")
        subprocess.run(["git", "add", "README.md", ".gitignore"], cwd=self.repo, check=True)
        subprocess.run(["git", "commit", "-m", "initial"], cwd=self.repo, check=True, capture_output=True)
        self.worktrees = self.tmp / "worktrees"
        self.artifacts = self.tmp / "artifacts"
        self.bin = self.tmp / "bin"
        self.bin.mkdir()
        codex = self.bin / "codex"
        codex.write_text(
            "#!/usr/bin/env python3\n"
            "from pathlib import Path\n"
            "import json\n"
            "Path('generated.txt').write_text('generated by test agent\\n', encoding='utf-8')\n"
            "print(json.dumps({'type':'result','response':'fixture success'}))\n",
            encoding="utf-8",
        )
        codex.chmod(0o755)
        self.old_path = os.environ.get("PATH", "")
        os.environ["PATH"] = str(self.bin) + os.pathsep + self.old_path

    def tearDown(self) -> None:
        os.environ["PATH"] = self.old_path
        self.temp.cleanup()

    def write_manifest(self, tasks: list[dict]) -> Path:
        path = self.tmp / "manifest.json"
        path.write_text(json.dumps({"version": 1, "max_parallel": 2, "tasks": tasks}), encoding="utf-8")
        return path

    def test_manifest_rejects_boolean_version_and_unknown_fields(self) -> None:
        payload = {"version": True, "tasks": []}
        path = self.tmp / "manifest.json"
        path.write_text(json.dumps(payload), encoding="utf-8")
        with self.assertRaises(agent_fleet.FleetError):
            agent_fleet.load_manifest(path)

        path.write_text(json.dumps({
            "version": 1, "unexpected": True, "tasks": [{
                "id": "valid-task", "agent": "codex", "mode": "implement",
                "allowed_paths": ["src/**"], "prompt": "work",
            }],
        }), encoding="utf-8")
        with self.assertRaisesRegex(agent_fleet.FleetError, "unsupported fields"):
            agent_fleet.load_manifest(path)

    def test_manifest_rejects_unknown_task_fields_and_duplicate_paths(self) -> None:
        base = {
            "id": "valid-task", "agent": "codex", "mode": "implement",
            "allowed_paths": ["src/**"], "prompt": "work",
        }
        path = self.write_manifest([{**base, "surprise": "ignored?"}])
        with self.assertRaisesRegex(agent_fleet.FleetError, "unsupported fields"):
            agent_fleet.load_manifest(path)
        path = self.write_manifest([{**base, "allowed_paths": ["src/**", "src/**"]}])
        with self.assertRaisesRegex(agent_fleet.FleetError, "cannot contain duplicates"):
            agent_fleet.load_manifest(path)

    def test_checked_in_example_manifest_matches_runtime_contract(self) -> None:
        example = Path(__file__).parents[1] / "agent-workers" / "tasks.example.json"
        manifest = agent_fleet.load_manifest(example)
        self.assertEqual(manifest["version"], 1)
        self.assertEqual(len(manifest["tasks"]), 2)
        self.assertEqual(manifest["max_parallel"], 2)

    def test_manifest_rejects_path_traversal(self) -> None:
        path = self.write_manifest([{
            "id": "unsafe-task", "agent": "codex", "mode": "implement",
            "allowed_paths": ["../outside.txt"], "prompt": "do work",
        }])
        with self.assertRaises(agent_fleet.FleetError):
            agent_fleet.load_manifest(path)

    def test_manifest_requires_scoped_paths_for_implementation(self) -> None:
        path = self.write_manifest([{
            "id": "missing-scope", "agent": "codex", "mode": "implement",
            "allowed_paths": [], "prompt": "do work",
        }])
        with self.assertRaises(agent_fleet.FleetError):
            agent_fleet.load_manifest(path)

    def test_manifest_rejects_non_directory_wildcard_globs(self) -> None:
        path = self.write_manifest([{
            "id": "wildcard-scope", "agent": "codex", "mode": "implement",
            "allowed_paths": ["src/**/*.py"], "prompt": "make a change",
        }])
        with self.assertRaisesRegex(agent_fleet.FleetError, "only exact paths or a trailing"):
            agent_fleet.load_manifest(path)

    def test_manifest_rejects_non_normalized_relative_paths(self) -> None:
        for unsafe in ("src//module.py", "src/./module.py", "C:/private.txt", "src\\\\private.txt"):
            path = self.write_manifest([{
                "id": "unsafe-path", "agent": "codex", "mode": "implement",
                "allowed_paths": [unsafe], "prompt": "make a change",
            }])
            with self.subTest(path=unsafe):
                with self.assertRaises(agent_fleet.FleetError):
                    agent_fleet.load_manifest(path)

    def test_manifest_rejects_overlapping_parallel_write_scopes(self) -> None:
        path = self.write_manifest([
            {
                "id": "worker-alpha", "agent": "codex", "mode": "implement",
                "allowed_paths": ["src/**"], "prompt": "work in source tree",
            },
            {
                "id": "worker-bravo", "agent": "codex", "mode": "implement",
                "allowed_paths": ["src/module.py"], "prompt": "change one module",
            },
        ])
        with self.assertRaisesRegex(agent_fleet.FleetError, "Overlapping write scopes"):
            agent_fleet.load_manifest(path)

    def test_aider_is_not_enabled_until_safe_noninteractive_mode_is_verified(self) -> None:
        path = self.write_manifest([{
            "id": "aider-disabled", "agent": "aider", "mode": "implement",
            "allowed_paths": ["src/**"], "prompt": "make a change",
        }])
        with self.assertRaisesRegex(agent_fleet.FleetError, "unsupported agent"):
            agent_fleet.load_manifest(path)

    def test_codex_adapter_keeps_workspace_sandbox_and_no_yolo(self) -> None:
        worktree = self.tmp / "w"
        prompt_file = self.tmp / "prompt.md"
        argv, stdin_text = agent_fleet.build_agent_command("codex", "implement", "task body", prompt_file, worktree)
        self.assertIn("workspace-write", argv)
        self.assertIn("--ephemeral", argv)
        self.assertIn("--ask-for-approval", argv)
        self.assertIn("never", argv)
        self.assertNotIn("--yolo", argv)
        self.assertEqual(stdin_text, "task body")
        review_argv, _ = agent_fleet.build_agent_command("codex", "review", "review", prompt_file, worktree)
        self.assertIn("read-only", review_argv)
        gemini_argv, _ = agent_fleet.build_agent_command("gemini", "implement", "task", prompt_file, worktree)
        self.assertIn("--approval-mode", gemini_argv)
        self.assertIn("auto_edit", gemini_argv)
        self.assertIn("--output-format", gemini_argv)
        gemini_review, _ = agent_fleet.build_agent_command("gemini", "review", "review", prompt_file, worktree)
        self.assertIn("plan", gemini_review)
        claude_argv, _ = agent_fleet.build_agent_command("claude", "implement", "task", prompt_file, worktree)
        self.assertIn("--no-session-persistence", claude_argv)
        self.assertIn("acceptEdits", claude_argv)
        claude_review, _ = agent_fleet.build_agent_command("claude", "review", "review", prompt_file, worktree)
        self.assertIn("plan", claude_review)

    def test_run_creates_worktree_patch_and_json_report(self) -> None:
        manifest_path = self.write_manifest([{
            "id": "make-generated-file", "title": "Generate fixture file", "agent": "codex",
            "mode": "implement", "base_ref": "HEAD", "allowed_paths": ["generated.txt"],
            "prompt": "Create generated.txt with a short fixture message.",
        }])
        args = argparse.Namespace(
            repo=str(self.repo),
            manifest=str(manifest_path),
            max_parallel=1,
            timeout=60,
            worktree_root=str(self.worktrees),
            artifacts_root=str(self.artifacts),
            capture_logs=True,
        )
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            exit_code = agent_fleet.run_fleet(args)
        self.assertEqual(exit_code, 0)
        run_report = json.loads(output.getvalue())
        self.assertTrue(run_report["requires_human_review"])
        self.assertEqual(run_report["status"], "completed")
        artifact_dir = Path(run_report["artifact_dir"])
        saved_report = json.loads((artifact_dir / "run.json").read_text(encoding="utf-8"))
        self.assertEqual(saved_report, run_report)
        result = run_report["tasks"][0]
        self.assertEqual(result["status"], "completed")
        self.assertTrue(result["logs_exported"])
        self.assertEqual(result["changed_files"], ["generated.txt"])
        patch_file = Path(result["patch_path"])
        patch = patch_file.read_text(encoding="utf-8")
        self.assertIn("generated by test agent", patch)
        self.assertEqual(result["patch_sha256"], hashlib.sha256(patch_file.read_bytes()).hexdigest())
        self.assertRegex(result["patch_sha256"], r"^[0-9a-f]{64}$")
        self.assertTrue(Path(result["stdout_path"]).exists())
        self.assertTrue(Path(run_report["tasks"][0]["worktree"], "generated.txt").exists())

    def test_scope_violation_is_not_reported_as_completed(self) -> None:
        manifest_path = self.write_manifest([{
            "id": "wrong-path", "agent": "codex", "mode": "implement", "base_ref": "HEAD",
            "allowed_paths": ["only-this.txt"], "prompt": "create a file",
        }])
        task = agent_fleet.load_manifest(manifest_path)["tasks"][0]
        artifact_dir = self.artifacts / "scope-test"
        worktree_root = self.worktrees / "scope-test"
        artifact_dir.mkdir(parents=True)
        worktree_root.mkdir(parents=True)
        prepared = agent_fleet.prepare_task(self.repo, task, "scope-test-12345678", worktree_root, artifact_dir)
        result = agent_fleet.execute_task(prepared, artifact_dir, timeout=60, capture_logs=True)
        self.assertEqual(result["status"], "scope_violation")
        self.assertFalse(result["logs_exported"])
        self.assertIsNone(result["stdout_path"])
        self.assertIsNone(result["stderr_path"])
        self.assertEqual(result["log_block_reason"], "scope_validation_failed")
        self.assertEqual(result["scope_violations"], ["generated.txt"])
        self.assertFalse(result["patch_exported"])
        self.assertIsNone(result["patch_path"])
        self.assertIsNone(result["patch_sha256"])
        self.assertEqual(result["patch_block_reason"], "scope_validation_failed")
        self.assertFalse((artifact_dir / "wrong-path.patch").exists())
        # The distinctive contents written by the fake CLI must not appear in
        # any handoff artifact when a task violates its path allowlist.
        for artifact in artifact_dir.iterdir():
            if artifact.is_file():
                self.assertNotIn("generated by test agent", artifact.read_text(encoding="utf-8"))
        self.assertFalse((artifact_dir / "wrong-path.stdout.txt").exists())
        self.assertFalse((artifact_dir / "wrong-path.stderr.txt").exists())

