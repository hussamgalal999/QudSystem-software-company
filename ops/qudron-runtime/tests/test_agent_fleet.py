    def test_run_creates_worktree_patch_and_json_report(self) -> None:
        manifest_path = self.write_manifest([{
            "id": "make-generated-file", "title": "Generate fixture file", "agent": "codex",
            "mode": "implement", "base_ref": "HEAD", "allowed_paths": ["generated.txt"],
            "prompt": "Create generated.txt with a short fixture message.",
            "acceptance_criteria": ["Only generated.txt changes."],
            "expected_checks": ["Review the patch and verify the changed-file manifest."],
            "known_risks": ["The local fixture uses a fake CLI; it does not exercise a model provider."],
        }])
        args = argparse.Namespace(
            repo=str(self.repo),
            manifest=str(manifest_path),
            max_parallel=1,
            timeout=60,
            worktree_root=str(self.worktrees),
            artifacts_root=str(self.artifacts),
            capture_logs=True,
        )
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            exit_code = agent_fleet.run_fleet(args)
        self.assertEqual(exit_code, 0)
        run_report = json.loads(output.getvalue())
        self.assertTrue(run_report["requires_human_review"])
        self.assertEqual(run_report["status"], "completed")
        artifact_dir = Path(run_report["artifact_dir"])
        saved_report = json.loads((artifact_dir / "run.json").read_text(encoding="utf-8"))
        self.assertEqual(saved_report, run_report)
        self.assertEqual(os.stat(artifact_dir).st_mode & 0o777, 0o700)
        self.assertEqual(os.stat(artifact_dir / "run.json").st_mode & 0o777, 0o600)
        result = run_report["tasks"][0]
        self.assertEqual(result["status"], "completed")
        self.assertTrue(result["logs_exported"])
        self.assertEqual(result["changed_files"], ["generated.txt"])
        self.assertEqual(result["allowed_paths"], ["generated.txt"])
        self.assertEqual(result["acceptance_criteria"], ["Only generated.txt changes."])
        self.assertEqual(result["expected_checks"], ["Review the patch and verify the changed-file manifest."])
        self.assertEqual(result["known_risks"], ["The local fixture uses a fake CLI; it does not exercise a model provider."])
        self.assertIn(".env", result["deny_paths"])
        self.assertNotIn("prompt", result)
        patch_file = Path(result["patch_path"])
        patch = patch_file.read_text(encoding="utf-8")
        self.assertIn("generated by test agent", patch)
        self.assertEqual(result["patch_sha256"], hashlib.sha256(patch_file.read_bytes()).hexdigest())
        self.assertRegex(result["patch_sha256"], r"^[0-9a-f]{64}$")
        self.assertTrue(Path(result["stdout_path"]).exists())
        self.assertTrue(Path(run_report["tasks"][0]["worktree"], "generated.txt").exists())

    def test_scope_violation_is_not_reported_as_completed(self) -> None:
        manifest_path = self.write_manifest([{
            "id": "wrong-path", "agent": "codex", "mode": "implement", "base_ref": "HEAD",
            "allowed_paths": ["only-this.txt"], "prompt": "create a file",
        }])
        task = agent_fleet.load_manifest(manifest_path)["tasks"][0]
        artifact_dir = self.artifacts / "scope-test"
        worktree_root = self.worktrees / "scope-test"
        artifact_dir.mkdir(parents=True)
        worktree_root.mkdir(parents=True)
        prepared = agent_fleet.prepare_task(self.repo, task, "scope-test-12345678", worktree_root, artifact_dir)
        result = agent_fleet.execute_task(prepared, artifact_dir, timeout=60, capture_logs=True)
        self.assertEqual(result["status"], "scope_violation")
        self.assertFalse(result["logs_exported"])
        self.assertIsNone(result["stdout_path"])
        self.assertIsNone(result["stderr_path"])
        self.assertEqual(result["log_block_reason"], "scope_validation_failed")
        self.assertEqual(result["scope_violations"], ["generated.txt"])
        self.assertFalse(result["patch_exported"])
        self.assertIsNone(result["patch_path"])
        self.assertIsNone(result["patch_sha256"])
        self.assertEqual(result["patch_block_reason"], "scope_validation_failed")
        self.assertFalse((artifact_dir / "wrong-path.patch").exists())
        # The distinctive contents written by the fake CLI must not appear in
        # any handoff artifact when a task violates its path allowlist.
        for artifact in artifact_dir.iterdir():
            if artifact.is_file():
                self.assertNotIn("generated by test agent", artifact.read_text(encoding="utf-8"))
        self.assertFalse((artifact_dir / "wrong-path.stdout.txt").exists())
        self.assertFalse((artifact_dir / "wrong-path.stderr.txt").exists())

